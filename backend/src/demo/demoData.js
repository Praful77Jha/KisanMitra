// MSAMB reference market prices. The Prisma seed script (backend/prisma/seed.js),
// the in-memory fallback controllers (products/offers/market-prices) and the demo
// data-integrity tests all read from this module so database mode and in-memory
// mode always expose the SAME demo records.
//
