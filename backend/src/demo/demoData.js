// re-seeding can never create duplicates (the seed wipes only the demo tables:
// product/requirement/offer/order/marketPrice — user accounts are NOT touched).
//
// Consumers:
//   - backend/prisma/seed.js        -> writes these rows to MySQL (see seed:demo)
//   - controllers/productsController -> in-memory GET /api/products fallback
//   - controllers/offersController   -> in-memory product-offer fallback
//   - services/marketPriceService    -> in-memory GET /api/market-prices fallback
//   - test/demoSeedIntegrity.test.js -> integrity + DB/in-memory parity checks

